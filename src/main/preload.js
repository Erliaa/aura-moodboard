const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('aura', {
  win: (a) => ipcRenderer.send('win', a),
  importUrl: (u) => ipcRenderer.invoke('files:url', u),
  saveText: (name, ext, text) => ipcRenderer.invoke('export:text', name, ext, text),
  savePdf: (d, w, h) => ipcRenderer.invoke('export:pdf', d, w, h),
  saveOriginals: (l) => ipcRenderer.invoke('export:originals', l),
  designOpts: (o) => ipcRenderer.send('design:opts', o),
  pickAudio: () => ipcRenderer.invoke('audio:pick'),
  importAudio: (ps) => ipcRenderer.invoke('audio:import', ps),
  linkMeta: (u) => ipcRenderer.invoke('meta:link', u),
  transcode: (f) => ipcRenderer.invoke('video:transcode', f),
  exportProject: (p, f, n) => ipcRenderer.invoke('project:export', p, f, n),
  importProject: (p) => ipcRenderer.invoke('project:import', p),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdates: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.send('update:install'),
  onUpdate: (cb) => ipcRenderer.on('update-status', (_e, d) => cb(d)),
  onOpenProject: (cb) => ipcRenderer.on('open-project', (_e, p) => cb(p)),
  openLink: (u) => ipcRenderer.send('link:open', u),
  fullscreen: (v) => ipcRenderer.send('win:fullscreen', v),
  toggleDesign: () => ipcRenderer.send('toggle-design'),
  onDesign: (cb) => ipcRenderer.on('design-mode', (_e, on) => cb(on)),
  load: () => ipcRenderer.invoke('state:load'),
  save: (s) => ipcRenderer.send('state:save', s),
  pick: () => ipcRenderer.invoke('files:pick'),
  importFiles: (ps) => ipcRenderer.invoke('files:import', ps),
  pathOf: (f) => webUtils.getPathForFile(f),
  importBuffer: (name, bytes) => ipcRenderer.invoke('files:buffer', name, bytes),
  saveVideo: (bytes, ext) => ipcRenderer.invoke('export:video', bytes, ext),
  read: (f) => ipcRenderer.invoke('file:read', f),
  del: (f) => ipcRenderer.send('file:delete', f),
  saveImage: (d) => ipcRenderer.invoke('export:save', d)
});
